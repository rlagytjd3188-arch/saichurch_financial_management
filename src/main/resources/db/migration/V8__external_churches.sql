CREATE TABLE EXTERNAL_CHURCH(
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 NAME VARCHAR(100) NOT NULL UNIQUE,
 ALIASES VARCHAR(500) NOT NULL DEFAULT '',
 NOTES VARCHAR(500) NOT NULL DEFAULT '',
 ACTIVE BOOLEAN NOT NULL DEFAULT TRUE
);
ALTER TABLE FINANCIAL_RECORD ADD COLUMN EXTERNAL_CHURCH_ID BIGINT REFERENCES EXTERNAL_CHURCH(ID);
ALTER TABLE FINANCIAL_RECORD ADD COLUMN EXTERNAL_CHURCH_MANUAL BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX IX_RECORD_EXTERNAL_CHURCH ON FINANCIAL_RECORD(EXTERNAL_CHURCH_ID,DATE);

