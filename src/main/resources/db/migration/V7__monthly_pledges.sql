-- 월 약정은 거래가 아니다. 시작·종료월별 약정 이력을 별도로 보존한다.
CREATE TABLE PLEDGE_COMMITMENT(
 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 CONTACT_ID BIGINT NOT NULL REFERENCES CONTACT(ID),
 MONTHLY_AMOUNT BIGINT NOT NULL CHECK(MONTHLY_AMOUNT>0),
 START_MONTH DATE NOT NULL,
 END_MONTH DATE,
 CANCELLED BOOLEAN NOT NULL DEFAULT FALSE,
 CHECK(END_MONTH IS NULL OR END_MONTH>=START_MONTH)
);
CREATE INDEX IX_PLEDGE_CONTACT_MONTH ON PLEDGE_COMMITMENT(CONTACT_ID,START_MONTH,END_MONTH);
